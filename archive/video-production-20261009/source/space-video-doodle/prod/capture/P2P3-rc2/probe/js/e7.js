const s = await get('phone');
const p = s.page;
const out = {};
const f = p.locator('.music-topics form[data-topic-create]');
await f.locator('input[name=title]').fill('晚班列车');
await f.locator('input[name=note]').fill('返场前那段鼓点，你们是不是也在跟着拍手？');
await f.locator('input[name=consent]').check();
await shot(p, 'e7-filled');
await f.locator('button').click();
await p.waitForSelector('.music-topics article.music-reference', { timeout: 20000 });
await sleep(1500);
out.card = await p.evaluate(() => document.querySelector('.music-topics article.music-reference')?.innerText.replace(/\s+/g, ' '));
out.topics = await p.evaluate(() => document.querySelector('.music-topics')?.innerText.replace(/\n{2,}/g, '\n'));
out.status = await p.evaluate(() => [...document.querySelectorAll('.music-topics [role=status], .music-topics [role=alert]')].map(e => e.textContent.trim()));
out.formAfter = await p.evaluate(() => { const f = document.querySelector('.music-topics form[data-topic-create]'); return f ? { open: f.closest('details')?.open, title: f.querySelector('[name=title]').value } : null; });
out.cardBox = await H.box(p, '.music-topics article.music-reference');
out.audit = await H.audit(p);
await shot(p, 'e7-posted');
return out;
