// Room -> 音乐探索 -> map -> 返回现场, one viewport. KIND=phone|desktop
const { launch, open, audit, outside, ORIGIN, mkdir } = require('./lib.cjs');
const KIND = process.env.KIND || 'phone';
const PREFIX = process.env.PREFIX || '/musicSpace/';
const OUT = mkdir(`/tmp/space-map/shots/verify/room-${KIND}${PREFIX.includes('preview') ? '-preview' : ''}`);
(async () => {
  const browser = await launch();
  const { ctx, page, rec } = await open(browser, KIND);
  await page.goto(ORIGIN + PREFIX, { waitUntil: 'load' });
  await page.waitForFunction(() => window.__SPACE_BOOT__ === 'ready', null, { timeout: 60000 });
  await page.waitForTimeout(2500);
  await page.screenshot({ path: `${OUT}/01-room.png` });
  const tap = async sel => { const l = page.locator(sel).filter({ visible: true }).first(); await l.waitFor({ state: 'visible', timeout: 30000 }); await l.scrollIntoViewIfNeeded().catch(() => {}); if (KIND !== 'desktop') await l.tap(); else await l.click(); };
  await tap('#join');
  await page.waitForSelector('form[data-form="demo-entry"]', { timeout: 30000 });
  await page.waitForTimeout(600);
  await tap('form[data-form="demo-entry"] label.consent');
  if (!(await page.isChecked('form[data-form="demo-entry"] input[name="consent"]'))) await page.check('form[data-form="demo-entry"] input[name="consent"]', { force: true });
  await page.waitForFunction(() => { const b = document.querySelector('form[data-form="demo-entry"] button[type="submit"]'); return b && !b.disabled; }, null, { timeout: 90000 });
  await tap('form[data-form="demo-entry"] button[type="submit"]');
  await page.waitForSelector('[data-tour-action]', { timeout: 60000 }).catch(() => console.log('no tour card'));
  await page.waitForTimeout(2000);
  await page.screenshot({ path: `${OUT}/01b-room-joined.png` });
  const entry = page.locator('#music-map-entry');
  console.log('entry visible:', await entry.isVisible(), 'text:', (await entry.innerText()).trim());
  const box = await entry.boundingBox(); console.log('entry box', box);
  await Promise.all([page.waitForURL(/music-map/, { timeout: 20000 }), KIND !== 'desktop' ? entry.tap() : entry.click()]);
  console.log('map url', page.url().replace(ORIGIN, ''));
  await page.waitForSelector('#sakura-world canvas', { timeout: 20000 }).catch(e => console.log('no canvas', String(e).slice(0, 100)));
  await page.waitForTimeout(6000);
  await page.screenshot({ path: `${OUT}/02-map-landing.png` });
  const a = await audit(page);
  console.log(JSON.stringify({ ...a, text: a.text.slice(0, 1500) }, null, 1));
  const actions = await page.$$eval('[data-map-action]', els => els.filter(e => e.checkVisibility()).map(e => `${e.dataset.mapAction}: ${(e.getAttribute('aria-label') || e.innerText).replace(/\s+/g, ' ').slice(0, 50)}`));
  console.log('ACTIONS', actions.join(' | '));
  const back = page.locator('.space-map-back');
  console.log('back visible', await back.isVisible());
  await Promise.all([page.waitForURL(u => !String(u).includes('music-map'), { timeout: 20000 }), back.click()]);
  console.log('back url', page.url().replace(ORIGIN, ''));
  await page.waitForFunction(() => window.__SPACE_BOOT__ === 'ready', null, { timeout: 60000 }).catch(e => console.log('room not ready', String(e).slice(0, 100)));
  await page.waitForTimeout(2500);
  await page.screenshot({ path: `${OUT}/03-room-again.png` });
  console.log('REC', JSON.stringify({ console: rec.console, pageerrors: rec.pageerrors, failed: rec.failed, bad: rec.bad, outside: outside(rec), popups: rec.popups }, null, 1));
  await ctx.close(); await browser.close();
})().catch(e => { console.error('FATAL', e); process.exit(1); });
