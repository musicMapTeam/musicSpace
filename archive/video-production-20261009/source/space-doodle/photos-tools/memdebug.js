const { chromium } = require('/tmp/space-video-prep/tools/node_modules/playwright-core');
const sleep = ms => new Promise(r => setTimeout(r, ms));
(async () => {
  const browser = await chromium.launch({ executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome' });
  const context = await browser.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, acceptDownloads: true });
  const page = await context.newPage();
  page.setDefaultTimeout(20000);
  await page.goto('http://127.0.0.1:5190/');
  await page.waitForFunction(() => window.__SPACE_BOOT__ === 'ready', null, { timeout: 60000 });
  await sleep(800);
  await page.locator('button', { hasText: '进入示例现场' }).first().click();
  await page.check('form[data-form="demo-entry"] input[name="consent"]');
  await page.waitForFunction(() => !document.querySelector('form[data-form="demo-entry"] button[type="submit"]')?.disabled);
  await page.click('form[data-form="demo-entry"] button[type="submit"]');
  await page.waitForSelector('[data-tour-action="sample:sample-crowd"]');
  await sleep(500);
  await page.click('[data-tour-action="sample:sample-crowd"]');
  await page.waitForSelector('form[data-form="upload"] .photo-review');
  await page.click('form[data-form="upload"] .moment-chip[data-moment-viewpoint="crowd"]');
  await page.click('form[data-form="upload"] button[type="submit"]');
  await page.waitForSelector('.moment-wall');
  await sleep(1000);
  await page.evaluate(() => document.querySelector('#panel-close')?.click());
  await sleep(500);
  const info = await page.evaluate(() => ({ recap: document.querySelector('#room-recap')?.outerHTML, opens: [...document.querySelectorAll('[data-open="recap"]')].map(b => b.outerHTML.slice(0, 200)) }));
  console.log(JSON.stringify(info, null, 1));
  await page.evaluate(() => document.querySelector('#room-recap')?.click());
  await sleep(2500);
  console.log(await page.evaluate(() => ({ kind: document.querySelector('#panel')?.dataset.kind, hidden: document.querySelector('#panel')?.hidden, btn: document.querySelector('[data-open="memory-card"]')?.outerHTML })));
  await page.click('.panel[data-kind="recap"] [data-open="memory-card"]');
  await sleep(1500);
  console.log(await page.evaluate(() => document.querySelector('#panel-body')?.innerHTML.slice(0, 3000)));
  await browser.close();
})().catch(e => { console.log('ERR', e.message); process.exit(1); });
