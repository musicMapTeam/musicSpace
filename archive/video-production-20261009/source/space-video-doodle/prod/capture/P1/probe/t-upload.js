S.startRecording('/tmp/space-video-doodle/prod/capture/P1/probe/t-upload.mp4');
await S.hold(0.5);
await S.click(p.locator('[data-tour-action="sample:sample-crowd"]'), { move: 0, pre: 0.1, post: 0 });
