// Item 3: open 小满·示例 from 同场的人, greet, wait for the example reply, chat, see the next example line.
const L = require('./jlib.js');
const vp = process.argv[2] || 'phone';
const channel = process.argv[3] || 'root';
const label = `social2-${channel}-${vp}`;
(async () => {
  const browser = await L.launch();
  const run = await L.open(browser, vp, { label });
  const { page } = run;
  const out = {}; const taps = [];
  const say = (k, v) => { out[k] = v; console.log(k, '=>', typeof v === 'string' ? v : JSON.stringify(v)); };
  try {
    await L.clearServerLog();
    await L.boot(page, L.baseUrl(channel));
    await L.tap(run, page.locator('#join'), '进入示例现场', taps);
    await page.waitForFunction(() => !document.querySelector('form[data-form="demo-entry"] button[type="submit"]')?.disabled, null, { timeout: 60000 });
    await L.tap(run, page.locator('form[data-form="demo-entry"] input[name="consent"]'), 'consent', taps);
    await L.tap(run, page.locator('form[data-form="demo-entry"] button[type="submit"]'), 'submit', taps);
    await page.waitForFunction(() => document.querySelector('.frame')?.dataset.stage === 'room', null, { timeout: 30000 });
    await L.sleep(1500);
    await L.tap(run, page.locator('.camera-nav [data-view="person"]'), '同场的人 (nav)', taps);
    const man = page.locator('#panel button[data-person]', { hasText: '小满' }).first();
    await man.waitFor({ state: 'visible', timeout: 20000 });
    say('people list', await page.evaluate(() => [...document.querySelectorAll('#panel button[data-person]')].map(b => b.innerText.trim().replace(/\s+/g, ' '))));
    await L.shot(run, 'people');
    await L.tap(run, man, '小满·示例', taps);
    const greet = page.locator('#panel [data-social-send]').first();
    const greetOk = await greet.waitFor({ state: 'visible', timeout: 20000 }).then(() => true).catch(() => false);
    say('person panel', await page.evaluate(() => document.querySelector('#panel-body')?.innerText.trim().replace(/\s+/g, ' ').slice(0, 300)));
    await L.shot(run, 'person');
    if (!greetOk) throw new Error('no greet button');
    say('greet text', (await greet.innerText()).trim());
    await L.tap(run, greet, '向 小满·示例 招个手', taps);
    const t0 = Date.now();
    const chatBtn = page.locator('#panel [data-open="chats"][data-id]').first();
    const friended = await chatBtn.waitFor({ state: 'visible', timeout: 40000 }).then(() => true).catch(() => false);
    say('accepted greeting', friended ? `${Date.now() - t0} ms` : 'NO (40 s)');
    say('person panel after greet', await page.evaluate(() => document.querySelector('#panel-body')?.innerText.trim().replace(/\s+/g, ' ').slice(0, 300)));
    say('inbox badge', await page.evaluate(() => { const c = document.querySelector('#social-count'); return c && !c.hidden ? c.textContent : '(hidden)'; }));
    await L.shot(run, 'person-friend');
    if (!friended) throw new Error('greeting not accepted');
    await L.tap(run, chatBtn, '和 小满·示例 私聊 ↗', taps);
    const welcome = await page.waitForFunction(() => /我是示例角色/.test(document.querySelector('.chat-messages')?.innerText || ''), null, { timeout: 20000 }).then(() => true).catch(() => false);
    say('welcome lines', welcome ? await page.evaluate(() => document.querySelector('.chat-messages')?.innerText.trim().replace(/\s+/g, ' ').slice(0, 300)) : 'NOT SHOWN');
    await L.shot(run, 'chat-welcome');
    await page.locator('#chat-text').fill('刚刚返场那首太好听了！');
    taps.push({ n: taps.length + 1, desc: '(typed a message)' });
    await L.tap(run, page.locator('.chat-composer button[type="submit"]'), '发送 ↗', taps);
    const t1 = Date.now();
    const reply = await page.waitForFunction(() => /今晚的返场太好听了/.test(document.querySelector('.chat-messages')?.innerText || ''), null, { timeout: 30000 }).then(() => true).catch(() => false);
    say('example reply', reply ? `${Date.now() - t1} ms` : 'NO REPLY in 30 s');
    say('thread', await page.evaluate(() => document.querySelector('.chat-messages')?.innerText.trim().replace(/\s+/g, ' ').slice(0, 500)));
    await L.sleep(800);
    await L.shot(run, 'chat-reply');
    const badge = () => page.evaluate(() => { const c = document.querySelector('#social-count'); return c && !c.hidden ? c.textContent : '(hidden)'; });
    await L.sleep(2500);
    say('badge with the thread open, reply read', await badge());
    await page.evaluate(() => {
      window.__scrollLog = [];
      const th = document.querySelector('.chat-thread'), t0 = performance.now();
      const rec = why => window.__scrollLog.push(`${Math.round(performance.now() - t0)}ms ${why} st=${Math.round(th.scrollTop)} sh=${th.scrollHeight} ch=${th.clientHeight} n=${th.querySelectorAll('.chat-message').length}`);
      new MutationObserver(() => rec('mut')).observe(th, { childList: true, subtree: true, characterData: true });
      th.addEventListener('scroll', () => rec('scroll'));
      new ResizeObserver(() => rec('resize')).observe(th);
      rec('start'); window.__scrollLog.push('heights at start: ' + ['.chat-notice', '.chat-problem', '.chat-pending', '.chat-composer', '.chat-composer small', '.chat-composer textarea'].map(sel => { const n = document.querySelector(sel); return sel + ':' + (n ? Math.round(n.getBoundingClientRect().height) : '-'); }).join(' '));
      const desc = Object.getOwnPropertyDescriptor(Element.prototype, 'scrollTop');
      Object.defineProperty(th, 'scrollTop', { configurable: true, get() { return desc.get.call(this); }, set(v) { desc.set.call(this, v); const hs = ['.chat-notice', '.chat-problem', '.chat-pending', '.chat-composer', '.chat-composer small', '.chat-composer textarea'].map(sel => { const n = document.querySelector(sel); return sel + ':' + (n ? Math.round(n.getBoundingClientRect().height) + (n.textContent.trim() ? '「' + n.textContent.trim().slice(0, 18) + '」' : '') : '-'); }).join(' '); window.__scrollLog.push(`${Math.round(performance.now() - t0)}ms SET ${Math.round(v)} -> st=${Math.round(desc.get.call(this))} sh=${this.scrollHeight} ch=${this.clientHeight} | ${hs}`); } });
      const sh = Object.getOwnPropertyDescriptor(Element.prototype, 'scrollHeight');
      window.__reads = 0;
    });
    await page.locator('#chat-text').fill('你拍的是人海吧？');
    await L.tap(run, page.locator('.chat-composer button[type="submit"]'), '发送 2', taps);
    const t2 = Date.now();
    const reply2 = await page.waitForFunction(n => (document.querySelector('.chat-messages')?.querySelectorAll('.chat-message.theirs').length || 0) > n, (await page.evaluate(() => document.querySelectorAll('.chat-messages .chat-message.theirs').length)), { timeout: 30000 }).then(() => true).catch(() => false);
    say('second reply', reply2 ? `${Date.now() - t2} ms` : 'NO REPLY in 30 s');
    say('thread 2', await page.evaluate(() => document.querySelector('.chat-messages')?.innerText.trim().replace(/\s+/g, ' ').slice(-160)));
    await L.sleep(2500);
    say('scrollers', await page.evaluate(() => { const m = el => el ? { sh: el.scrollHeight, ch: el.clientHeight, st: Math.round(el.scrollTop), oy: getComputedStyle(el).overflowY } : null; const last = [...document.querySelectorAll('.chat-messages .chat-message')].at(-1); const r = last?.getBoundingClientRect(); const tr = document.querySelector('.chat-thread')?.getBoundingClientRect(); return { thread: m(document.querySelector('.chat-thread')), messages: m(document.querySelector('.chat-messages')), root: m(document.querySelector('.private-chat')), lastMsg: r && [Math.round(r.top), Math.round(r.bottom)], threadRect: tr && [Math.round(tr.top), Math.round(tr.bottom)], winH: innerHeight, incoming: [...document.querySelectorAll('.chat-messages [data-incoming]')].map(n => n.innerText.slice(0, 12)) }; }));
    await L.shot(run, 'second-reply');
    say('scrollLog', await page.evaluate(() => window.__scrollLog.slice(0, 60)));
    say('badge after the second reply, thread open', await badge());
    await page.locator('.chat-close').click();
    await L.sleep(3000);
    say('badge after closing the chat', await badge());
    say('incoming greetings', await page.evaluate(() => (window.__SPACE_EVENT_QA__?.()?.social?.incoming || []).length));
    await page.evaluate(() => { const b = document.createElement('button'); b.dataset.open = 'chats'; b.style.position = 'fixed'; b.style.left = '-9999px'; document.body.append(b); b.click(); b.remove(); });
    await L.sleep(2500);
    say('chat list unread marks', await page.evaluate(() => [...document.querySelectorAll('.chat-conversations [data-chat-peer]')].map(b => b.innerText.replace(/\s+/g, ' ').slice(0, 80) + ' | unread=' + (b.querySelector('i')?.textContent || 0))));
    await page.locator('.chat-close').click();
    await L.sleep(2500);
    say('badge after the list', await badge());
    await L.shot(run, 'after-close');
  } catch (e) { say('FAILED', e.message.split('\n')[0]); await L.shot(run, 'failure').catch(() => {}); }
  say('taps', taps.map(t => `${t.n}. ${t.desc}${t.inView === false ? ' [SCROLL]' : ''}`));
  say('console', run.consoleMsgs); say('pageErrors', run.pageErrors);
  const net = L.summarizeNet(run); say('net', { total: net.total, api: net.api.length, external: net.external.length, bad: net.bad.map(r => `${r.status} ${r.url}`) });
  L.writeJson(`${label}.json`, out);
  await browser.close();
})();
